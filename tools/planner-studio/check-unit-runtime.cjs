'use strict';
const fs=require('node:fs'),path=require('node:path'),assert=require('node:assert/strict');
const workbook=require('./app/content-workbook.cjs'),engine=workbook.engine();
const {unitRuntime}=require('./app/unit-runtime.cjs');
const {encodeConfigRows}=require('./app/chart-payload.cjs');
const project=engine.Studio.create(),config=unitRuntime(project);
assert.equal(config.Units.length,5);
assert(config.Units.every(u=>u.Stats.length===4));
assert(!JSON.stringify(config).includes('Assets/'));
assert.equal(config.Units[0].Stats[0].AttackFrequency,project.tables.UnitBaseStat[0].AttackInterval);
const edited=engine.Studio.clone(project);edited.tables.Unit[0].UnitKey='renamed_key';
edited.tables.UnitBaseStat[0].Attack=777;
assert.equal(unitRuntime(edited).Units[0].AssetKey,config.Units[0].AssetKey);
assert.equal(unitRuntime(edited).Units[0].Stats[0].Attack,777);
const missing=engine.Studio.clone(project);missing.tables.UnitBaseStat.shift();assert.throws(()=>unitRuntime(missing));
const duplicate=engine.Studio.clone(project);duplicate.tables.Unit[1].Source=duplicate.tables.Unit[0].Source;assert.throws(()=>unitRuntime(duplicate));
const invalid=engine.Studio.clone(project);invalid.tables.UnitBaseStat[0].Attack=null;assert.throws(()=>unitRuntime(invalid));
const rows=encodeConfigRows(config,'unit-runtime-validation');
const restored=JSON.parse(Buffer.from(rows.slice(1).map(r=>r[5]).join(''),'base64').toString('utf8'));
assert.deepEqual(restored,JSON.parse(JSON.stringify(config)));
const out=path.resolve(__dirname,'../../outputs/unit-runtime');fs.mkdirSync(out,{recursive:true});
fs.writeFileSync(path.join(out,'config.json'),JSON.stringify(config));
fs.writeFileSync(path.join(out,'rows.json'),JSON.stringify(rows.slice(1).map(r=>Object.fromEntries(rows[0].map((k,i)=>[k,r[i]])))));
console.log('PASS: unit runtime export, stable asset mapping, frequency units, edited values, missing tiers/duplicate mappings/null rejection, payload roundtrip');
