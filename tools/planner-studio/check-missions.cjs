'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path');
const x=require('./app/content-workbook.cjs'),e=x.engine(),p=e.Studio.create(),names=x.bundles.missions;
const restored=x.read(x.write(p,names),p).project;
assert.equal(restored.tables.DataBindings.length,6);
assert.equal(restored.tables.Missions.length,9);
assert.equal(restored.tables.MissionEvents[0].Enabled,false);
const legacy=e.Studio.clone(p);for(const name of names)delete legacy.tables[name];
assert.equal(e.Studio.shape(legacy).tables.DataBindings.length,6);
const bad=e.Studio.clone(p);bad.tables.DataBindings[0].DataKey='NotInCode';assert.throws(()=>x.write(bad,names));
const duplicate=e.Studio.clone(p);duplicate.tables.DataBindings.push({...duplicate.tables.DataBindings[0],BindingKey:'duplicate'});assert.throws(()=>x.write(duplicate,names));
const source=e.Studio.clone(p);source.tables.DataBindings[0].ValueSource='MissingValue';assert.throws(()=>x.write(source,names));
const date=e.Studio.clone(p);date.tables.MissionEvents[0].EndAt=date.tables.MissionEvents[0].StartAt;assert.throws(()=>x.write(date,names));
const empty=e.Studio.clone(p);empty.tables.DataBindings=[];assert.throws(()=>x.write(empty,names));
const catalog=JSON.parse(fs.readFileSync(path.join(__dirname,'app/ui/content/event-catalog.json'),'utf8'));
assert.deepEqual(JSON.parse(JSON.stringify(e.EVENT_CATALOG)),catalog);
const config=x.toRuntime(p,names);assert.equal(config.CatalogVersion,catalog.version);assert.equal(config.Missions[0].Rewards[0].itemId,'Gold');
const output=path.join(__dirname,'tests/runtime/config.json');fs.mkdirSync(path.dirname(output),{recursive:true});fs.writeFileSync(output,JSON.stringify(config,null,2));
console.log('PASS: mission workbook roundtrip, legacy migration, invalid keys/sources/duplicates/dates, runtime JSON');
