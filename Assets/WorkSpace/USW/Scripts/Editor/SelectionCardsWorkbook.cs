using System;
using System.Collections.Generic;
using System.Globalization;
using System.IO;
using System.Linq;
using System.Text;
using GGD.BackendCharts;
using LitJson;
using UnityEditor;
using UnityEngine;

/// <summary>
/// Editor-only bridge between the authoring workbook <c>Data/Balance/SelectionCards.xlsx</c> and the bundled level-up card assets
/// (user decision 2026-11-11: Excel is the source; bundled values and the BACKND chart are both made from it).
/// The same workbook is uploaded to DEV_SelectionCards, then LIVE_SelectionCards. Never opened by a player build.
/// </summary>
public static class SelectionCardsWorkbook
{
    public const string SourcePath = "Data/Balance/SelectionCards.xlsx";
    public const string SheetName = "SelectionCards";
    public const string KeysPath = "Assets/WorkSpace/USW/Scripts/BackendCharts/SelectionCardsKeys.cs";
    private const string PoolPath = "Assets/WorkSpace/USW/Data/SelectionData/DroneLevelUpPool.asset";

    [MenuItem("Tools/Balance/SelectionCards.xlsx 검사 (업로드 전)")]
    public static void CheckMenu() => Debug.Log(Check(SourcePath));

    [MenuItem("Tools/Balance/SelectionCards.xlsx 값을 앱 내장 값에 반영")]
    public static void ImportMenu() => Debug.Log(Import(SourcePath));

    [MenuItem("Tools/Balance/SelectionCards 키 목록 다시 만들기 (카드나 효과를 추가한 뒤)")]
    public static void GenerateKeysMenu() => Debug.Log(GenerateKeys());

    /// <summary>Cards of the drone level-up pool by chooseId.</summary>
    public static SortedDictionary<int, LevelUpData> Cards()
    {
        var pool = AssetDatabase.LoadAssetAtPath<LevelUpPoolData>(PoolPath);
        if (pool == null) throw new InvalidOperationException("풀 에셋이 없다: " + PoolPath);
        var result = new SortedDictionary<int, LevelUpData>();
        foreach (var card in pool.Cards)
            if (card != null && card.EffectSchemaVersion == 1) result[card.chooseId] = card;
        return result;
    }

    /// <summary>Every chart key the assets ask for with its bundled value text, in card order. Whole-number keys are listed in <paramref name="whole"/>.</summary>
    public static List<KeyValuePair<string, string>> AssetRows(HashSet<string> whole = null)
    {
        var rows = new List<KeyValuePair<string, string>>();
        foreach (var card in Cards().Values)
        {
            rows.Add(new KeyValuePair<string, string>(card.chooseId + "." + SelectionCards.Enabled, "1"));
            rows.Add(new KeyValuePair<string, string>(card.chooseId + "." + SelectionCards.TierName, ((int)card.tier).ToString(CultureInfo.InvariantCulture)));
            foreach (var slot in SelectionCards.Slots(card.Composition))
                foreach (var field in SelectionCards.NumberFields(slot.Value.GetType()))
                {
                    string key = card.chooseId + "." + slot.Key + "." + field.Name;
                    rows.Add(new KeyValuePair<string, string>(key, N(Convert.ToSingle(field.GetValue(slot.Value)))));
                    if (field.FieldType == typeof(int)) whole?.Add(key);
                }
        }
        return rows;
    }

    /// <summary>Bundled value of every chart key, in chart text form.</summary>
    public static Dictionary<string, string> Bundled()
    {
        var result = new Dictionary<string, string>();
        foreach (var pair in AssetRows()) result.Add(pair.Key, pair.Value);
        foreach (string key in SelectionCards.Rules.Keys)
            if (!result.ContainsKey(key)) throw new InvalidOperationException("차트 키 " + key + ": 카드 에셋에 해당 값이 없다. 키 목록을 다시 만든다.");
        foreach (string key in result.Keys)
            if (!SelectionCards.Rules.ContainsKey(key)) throw new InvalidOperationException("카드 에셋의 값 " + key + ": 차트 키 목록에 없다. 키 목록을 다시 만든다.");
        return result;
    }

    /// <summary>Rewrites SelectionCardsKeys.cs from the pool assets. Run after adding a card or an effect, then add the new rows to the workbook.</summary>
    public static string GenerateKeys()
    {
        var whole = new HashSet<string>();
        var rows = AssetRows(whole);
        var ids = Cards().Keys.ToList();
        var text = new StringBuilder();
        text.Append("// Generated by the menu Tools/Balance/SelectionCards 키 목록 다시 만들기 (SelectionCardsWorkbook.GenerateKeys). Do not edit by hand.\n");
        text.Append("namespace GGD.BackendCharts\n{\n    /// <summary>Key list of the SelectionCards chart. A separate class so the lists exist before SelectionCards builds its rules.</summary>\n    public static class SelectionCardsKeys\n    {\n");
        text.Append("        public static readonly int[] CardIds = { ").Append(string.Join(", ", ids)).Append(" };\n");
        void Keys(string name, IEnumerable<string> keys)
        {
            text.Append("        public static readonly string[] ").Append(name).Append(" =\n        {\n");
            foreach (string key in keys) text.Append("            \"").Append(key).Append("\",\n");
            text.Append("        };\n");
        }
        var numbers = rows.Select(row => row.Key).Where(key => !key.EndsWith("." + SelectionCards.Enabled) && !key.EndsWith("." + SelectionCards.TierName)).ToList();
        Keys("WholeKeys", numbers.Where(whole.Contains));
        Keys("FloatKeys", numbers.Where(key => !whole.Contains(key)));
        text.Append("    }\n}\n");
        File.WriteAllText(KeysPath, text.ToString(), new UTF8Encoding(false));
        AssetDatabase.ImportAsset(KeysPath);
        return "SelectionCardsKeys.cs: 카드 " + ids.Count + "장, 키 " + rows.Count + "개";
    }

    /// <summary>Reads and validates the workbook with the rules the game applies to the chart.</summary>
    public static Dictionary<string, float[]> Read(string path)
    {
        var table = BalanceXlsxTable.Read(File.ReadAllBytes(path), SheetName, 1, "Key", "Value");
        var rows = new JsonData(); rows.SetJsonType(JsonType.Array);
        foreach (var row in table.Rows)
        {
            var item = new JsonData();
            item["Key"] = row.Get("Key") ?? "";
            item["Value"] = row.Get("Value") ?? "";
            rows.Add(item);
        }
        return SelectionCards.Parse(rows);
    }

    /// <summary>
    /// Problems the per-effect rules find when <paramref name="values"/> are applied to the cards (empty = none).
    /// Login only checks the chart shape, so this is the check that keeps a bad number out of a run.
    /// </summary>
    public static List<string> EffectProblems(Dictionary<string, float[]> values)
    {
        if (EditorApplication.isPlayingOrWillChangePlaymode) throw new InvalidOperationException("Exit Play mode before checking card balance.");
        var problems = new List<string>();
        try
        {
            SelectionCards.Chart.Install(values);
            foreach (var card in Cards().Values)
                try { SelectionDefinitionReader.CopyDefinition(card); }
                catch (Exception error) { problems.Add(card.chooseId + " " + card.chooseName + ": " + error.Message); }
        }
        finally { SelectionCards.Chart.Clear(); }
        return problems;
    }

    public static string Check(string path)
    {
        var workbook = Read(path);
        var bundled = Bundled();
        var lines = new List<string> { "SelectionCards.xlsx 형식 통과: 키 " + workbook.Count + "개" };
        var problems = EffectProblems(workbook);
        foreach (string problem in problems) lines.Add("효과 규칙 위반 " + problem);
        int before = lines.Count;
        foreach (var pair in workbook)
        {
            string excel = N(pair.Value[0]);
            if (bundled[pair.Key] != excel) lines.Add("다름 " + pair.Key + ": 엑셀 " + excel + " / 앱 내장 " + bundled[pair.Key]);
        }
        if (lines.Count == before) lines.Add("앱 내장 값과 전부 같음");
        if (problems.Count == 0) lines.Add("효과 규칙 통과: 카드 " + Cards().Count + "장");
        return string.Join("\n", lines);
    }

    /// <summary>Writes workbook numbers and tiers into the bundled card assets after the whole workbook passed validation.</summary>
    public static string Import(string path)
    {
        if (EditorApplication.isPlayingOrWillChangePlaymode) throw new InvalidOperationException("Exit Play mode before importing card balance.");
        var workbook = Read(path);
        var problems = EffectProblems(workbook);
        if (problems.Count > 0) throw new InvalidOperationException("효과 규칙 위반, 반영하지 않음:\n" + string.Join("\n", problems));
        var off = new List<string>();
        foreach (var card in Cards().Values)
        {
            Undo.RecordObject(card, "Import SelectionCards.xlsx");
            if (workbook[card.chooseId + "." + SelectionCards.Enabled][0] == 0f) off.Add(card.chooseId.ToString());
            card.tier = (Tier)Mathf.RoundToInt(workbook[card.chooseId + "." + SelectionCards.TierName][0]);
            foreach (var slot in SelectionCards.Slots(card.Composition))
                foreach (var field in SelectionCards.NumberFields(slot.Value.GetType()))
                {
                    float value = workbook[card.chooseId + "." + slot.Key + "." + field.Name][0];
                    field.SetValue(slot.Value, field.FieldType == typeof(int) ? (object)Mathf.RoundToInt(value) : value);
                }
            EditorUtility.SetDirty(card);
            AssetDatabase.SaveAssetIfDirty(card);
        }
        return "SelectionCards.xlsx 값을 앱 내장 값에 반영함: 키 " + workbook.Count + "개"
            + (off.Count > 0 ? "\n주의: 켜고 끄기는 차트에서만 적용된다(튜토리얼과 에디터 직접 실행은 전부 켜짐). 끈 카드: " + string.Join(", ", off) : "");
    }

    public static string N(float value) => ((double)(decimal)value).ToString("0.######", CultureInfo.InvariantCulture);
}
