/// <summary>
/// 중앙 알림 연출 방식 (시안 6종, 2026-10-02). 하나로 정해지면 나머지는 지워도 된다.
/// A·B·C는 모던(깔끔한 고딕 + 어두운 유리 바탕 + 강조색 하나 + 빠른 스냅), D는 게임 글꼴 그대로.
/// 정수값은 설정 에셋에 저장되므로 순서를 바꾸지 않는다.
/// </summary>
public enum CenterToastStyle
{
    /// <summary>A 스택 — 참고 GIF(중앙팝업1)처럼 연타하면 새 줄이 아래에 생기고 이전 줄은 위로 밀리며 작아지고 흐려진다. 줄마다 작은 유리 캡슐 + 강조 점.</summary>
    Stack = 0,
    /// <summary>B 라인 스플릿 — 강조선 두 줄이 가운데서 뻗었다 위아래로 갈라지며 유리 패널이 열리고 글자가 가운데서 바깥으로 드러난다. 연타하면 닫혔다 다시 열린다.</summary>
    LineSplit = 1,
    /// <summary>C 글래스 슬라이드 — 강조 막대가 달린 둥근 유리 카드가 오른쪽에서 쏘아져 들어오고 글자가 빠르게 타이핑된다. 연타하면 이전 카드가 왼쪽으로 빠지며 교체된다.</summary>
    GlassSlide = 2,
    /// <summary>D 펀치 글자 — 바탕 없이 게임 글꼴 글자만 크게 → 꽉 박힌다. 다시 누르면 이전 글자가 터지며 새 글자가 박힌다.</summary>
    PunchText = 3,
    /// <summary>E = B 디자인 + A 연출 — 줄마다 B의 라인 패널이 열리고, 연타하면 새 줄이 아래에 생기며 이전 줄은 위로 밀려 흐려진다.</summary>
    StackLines = 4,
    /// <summary>F = B 디자인 + C 연출 — B의 라인 패널이 오른쪽에서 쏘아져 들어오고 글자가 타이핑된다. 연타하면 이전 패널이 왼쪽으로 빠지며 교체.</summary>
    SlideLines = 5,
}
